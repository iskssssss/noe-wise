/** 图标只表达已授权菜单的业务含义，不参与菜单排序或权限判断。 */
export function navigationIcon(path?: string) {
  const parts = path?.split('/').filter(Boolean) ?? []
  const key = parts[1] === 'foundation' ? parts[2] : parts[1]
  return icons[key as keyof typeof icons] ?? CircleHelp
}
