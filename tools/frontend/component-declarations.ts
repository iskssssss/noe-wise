import { randomUUID } from 'node:crypto';
import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute, relative, resolve } from 'node:path';
import type { Plugin } from 'vite';
import { pascalCase, type ComponentResolver, type ComponentResolverObject } from 'unplugin-vue-components';

type Imports = Map<string, string>;

/** 接收现有公开 resolver 的结果；自动导入仍由 unplugin-vue-components 执行。 */
export function componentDeclarations(resolvers: ComponentResolver[]) {
  const components: Imports = new Map([
    ['RouterLink', "typeof import('vue-router')['RouterLink']"],
    ['RouterView', "typeof import('vue-router')['RouterView']"],
  ]);
  const directives: Imports = new Map();
  let filepath = '';
  let serving = false;
  let written = '';
  let pending: Promise<void> = Promise.resolve();

  function declarations(name: string, imports: Imports) {
    if (!imports.size) return '';
    const entries = [...imports].sort(([a], [b]) => a.localeCompare(b)).map(([key, value]) =>
      `    ${/^\w+$/.test(key) ? key : JSON.stringify(key)}: ${value}`);
    return `\n  export interface ${name} {\n${entries.join('\n')}\n  }`;
  }

  function publish() {
    const content = `/* eslint-disable */\n// @ts-nocheck\n// Generated by SkillForge component-declarations\nexport {}\n\ndeclare module 'vue' {${declarations('GlobalComponents', components)}${declarations('GlobalDirectives', directives)}\n}\n`;
    // 每次发布都归入同一队列，且失败交还 Vite 生命周期，避免游离 Promise 和重叠写入。
    pending = pending.then(async () => {
      if (content === written) return;
      await mkdir(dirname(filepath), { recursive: true });
      const temporary = `${filepath}.${process.pid}.${randomUUID()}.tmp`;
      try {
        await writeFile(temporary, content, { encoding: 'utf8', flag: 'wx' });
        await rename(temporary, filepath);
        written = content;
      } finally { await rm(temporary, { force: true }); }
    });
    return pending;
  }

  const tracked = resolvers.map(candidate => {
    const resolver = typeof candidate === 'function' ? { type: 'component' as const, resolve: candidate } : candidate;
    return {
      type: resolver.type,
      async resolve(name: string) {
        const result = await resolver.resolve(name);
        if (result) {
          const info = typeof result === 'string' ? { from: result } : result;
          const key = info.as ?? (resolver.type === 'directive' ? `v${pascalCase(name)}` : name);
          if (!key) return result;
          const from = (isAbsolute(info.from) ? `./${relative(dirname(filepath), info.from)}` : info.from).replaceAll('\\', '/');
          const value = `typeof import(${JSON.stringify(from)})[${JSON.stringify(info.name || 'default')}]`;
          const imports = resolver.type === 'directive' ? directives : components;
          if (imports.get(key) !== value) {
            imports.set(key, value);
            if (serving) await publish();
          }
        }
        return result;
      },
    } satisfies ComponentResolverObject;
  });

  const plugin: Plugin = {
    name: 'skillforge:component-declarations',
    // Vitest 只消费组件转换，不占用应用声明文件。
    apply: () => process.env.VITEST !== 'true',
    async configResolved(config) {
      filepath = resolve(config.root, 'src/components.d.ts');
      serving = config.command === 'serve';
      // 开发态只转换已访问模块，保留尚未访问页面的已有声明；完整构建重建当前集。
      if (serving) {
        try { written = await readFile(filepath, 'utf8'); }
        catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
        for (const [name, imports] of [['GlobalComponents', components], ['GlobalDirectives', directives]] as const) {
          const block = written.match(new RegExp(`interface\\s+${name}\\s*\\{([^}]*)\\}`))?.[1] ?? '';
          for (const match of block.matchAll(/^\s*(?:'([^']+)'|"([^"]+)"|(\w+))\s*:\s*(typeof import\(.+?\)\[.+?\])[,;]?\s*$/gm)) {
            imports.set((match[1] ?? match[2] ?? match[3])!, match[4]!);
          }
        }
        await publish();
      }
    },
    async buildEnd(error) { if (!serving && !error) await publish(); },
  };
  return { resolvers: tracked, plugin };
}
