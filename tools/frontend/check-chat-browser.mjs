import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(new URL('../../frontend-admin/package.json', import.meta.url));
const { chromium } = require('@playwright/test');
import { publicChatScenario, assertPublicVisibility, chatInputLimits } from './chat-public-browser-fixture.mjs';
const origin = process.env.CHAT_TEST_ORIGIN || 'http://127.0.0.1:3200';
const screenshotRoot = new URL('../../.runtime-logs/chat-process-browser/', import.meta.url);
await mkdir(screenshotRoot, { recursive: true });
const ok = data => ({ code: 'OK', message: 'OK', data, trace_id: 'chat-browser-check' });
const scenario = publicChatScenario();
const browser = await chromium.launch({ headless: true });
let diagnosticPage;
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage(); diagnosticPage = page; page.setDefaultTimeout(10_000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.route('**/api/v1/**', async route => {
    const request = route.request(), url = new URL(request.url());
    assert.equal(request.headers()['x-channel-token'], 'browser-token');
    let body;
    switch (url.pathname) {
      case '/api/v1/chat/agents': body = { channel_id: 'channel-1', items: [{ id: 'agent-1', name: '测试助手', is_default: true, delegation_config: { enabled: false, target_agent_ids: [] } }] }; break;
      case '/api/v1/chat/teams': body = []; break;
      case '/api/v1/chat/client-profile': body = { end_user_id: '101', display_name: '浏览器用户', channel_id: 'channel-1' }; break;
      case '/api/v1/chat/sessions': body = request.method() === 'POST' ? { session_id: 'session-1' } : [{ session_id: 'session-1', summary: '过程折叠验收', message_count: 2, agent_id: 'agent-1' }]; break;
      case '/api/v1/chat': body = scenario.submit(request.postDataJSON()); break;
      case '/api/v1/chat/events': assert.equal(request.method(), 'GET'); await scenario.events(route); return;
      case '/api/v1/chat/history': body = scenario.history(); break;
      case '/api/v1/chat/limits': body = chatInputLimits; break;
      case '/api/v1/chat/sessions/deliverables': case '/api/v1/chat/sessions/attachments': body = []; break;
      case '/api/v1/chat/commands': body = { items: [] }; break;
      case '/api/v1/chat/runs/collaboration': body = { active: false, pending: false, selected_active: false, todos: [] }; break;
      case '/api/v1/chat/runs/steering': body = { run_id: 'run-1', accepting: false, items: [] }; break;
      case '/api/v1/chat/work': body = null; break;
      case '/api/v1/chat/work/history': body = { items: [] }; break;
      case '/api/v1/chat/goals': body = { goal: null, continuation_enabled: false }; break;
      default: throw new Error(`Unexpected path ${url.pathname}`);
    }
    await route.fulfill({ json: ok(body) });
  });
  await page.goto(origin);
  await page.locator('.setup .el-select').click();
  await page.getByRole('option', { name: '渠道令牌', exact: true }).click();
  await page.getByLabel('渠道令牌', { exact: true }).fill('browser-token');
  await page.getByRole('button', { name: '验证并继续' }).click();
  await page.getByLabel('昵称').fill('浏览器用户');
  await page.getByRole('button', { name: '进入聊天' }).click();
  await page.locator('.conversation-sidebar__item').filter({ hasText: '测试助手' }).click();
  await page.getByLabel('消息', { exact: true }).fill('计算这组数据的平均值');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  const group = page.locator('.process-group').first();
  await group.locator('.process-item').nth(1).waitFor();
  assert.equal(await group.locator('.process-item').count(), 2);
  assert.equal(await group.locator('.process-group-toggle').getAttribute('aria-expanded'), 'true');
  scenario.stages.second.resolve();
  await group.locator('.process-item').nth(3).waitFor();
  await page.getByText('总和 45，平均值 9.0。', { exact: true }).waitFor();
  assert.equal(await group.locator('.process-group-toggle').getAttribute('aria-expanded'), 'true');
  assert.equal(await group.locator('.process-commentary').count(), 2);
  assert.deepEqual(await group.locator('.process-item').evaluateAll(items => items.map(item => item.classList.contains('type-commentary') ? 'commentary' : 'tool')), ['commentary', 'tool', 'commentary', 'tool']);
  assert.match(await group.locator('.process-item').nth(0).innerText(), /先读取订单数据/);
  await group.locator('.process-item-toggle').first().click();
  assert.equal(await group.getByRole('cell', { name: 'ORD-101' }).count(), 1);
  await assertPublicVisibility(page);
  await page.screenshot({ path: fileURLToPath(new URL('chat-process-expanded.png', screenshotRoot)), fullPage: true });
  scenario.stages.completion.resolve();
  await group.locator('.process-group-toggle[aria-expanded="false"]').waitFor();
  assert.equal(await group.locator('.process-item').count(), 0);
  await group.locator('.process-group-toggle').click();
  scenario.stages.replay.resolve();
  await group.getByText('再次核验数据一致', { exact: true }).waitFor();
  assert.equal(await group.locator('.process-group-toggle').getAttribute('aria-expanded'), 'true');
  await assertPublicVisibility(page);
  await group.getByRole('button', { name: '订单数据', exact: true }).click();
  assert.match(await page.locator('.composer-reference').innerText(), /订单数据/);
  await page.getByLabel('消息', { exact: true }).fill('继续生成报表');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  const inputCard = page.locator('.tool-input-card').filter({ hasText: '补充报表名称' }).last();
  await inputCard.getByLabel('报表名称', { exact: true }).fill('月度订单汇总');
  await assertPublicVisibility(page);
  await inputCard.getByRole('button', { name: '提交', exact: true }).click();
  await page.getByText('报表名称已确认。', { exact: true }).waitFor();
  assert.equal(scenario.posts.length, 3);
  assert.equal(await page.locator('article.message.user').count(), 2);
  await page.setViewportSize({ width: 390, height: 844 });
  const themeButton = page.getByRole('button', { name: /深色/ });
  if (await themeButton.count()) await themeButton.click();
  assert.ok((await group.boundingBox()).width <= 390);
  await assertPublicVisibility(page);
  await page.screenshot({ path: fileURLToPath(new URL('chat-process-mobile-dark.png', screenshotRoot)), fullPage: true });
  assert.deepEqual(errors, []);
  console.log('chat: typed text/table/reference, two stages, single POST per input, persistent GET, final/version guard, collapse once/manual, exact ToolWait, narrow/dark/reduced-motion PASS');
  await context.close();
} catch (error) {
  if (diagnosticPage && !diagnosticPage.isClosed()) {
    console.error('browser diagnostic', diagnosticPage.url(), await diagnosticPage.locator('body').innerText());
    console.error('process DOM', await diagnosticPage.locator('.process-group').evaluateAll(items => items.map(item => item.outerHTML)));
    await diagnosticPage.screenshot({ path: fileURLToPath(new URL('chat-process-failed.png', screenshotRoot)), fullPage: true });
  }
  throw error;
} finally { await browser.close(); }
