#!/usr/bin/env python3
"""生成后端模块依赖图（module graph）。

来源：backend-java/settings.gradle.kts（模块清单）+
      各模块 build.gradle.kts 中的生产 project(":...") 依赖。
产物：docs/08-数据与工具/generated/module-graph.md（带生成头，禁止手改）。

用法：
    python tools/docs/gen_module_graph.py            # 生成并写入产物
    python tools/docs/gen_module_graph.py --check    # 校验产物新鲜度（CI）

退出码：--check 且产物与生成结果不一致时为 1。
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
BACKEND = ROOT / "backend-java"
OUT = ROOT / "docs/08-数据与工具/generated/module-graph.md"
GEN_HEADER = "<!-- Generated by tools/docs/gen_module_graph.py — do not edit by hand. Run: make docs-regenerate -->\n"

INCLUDE_RE = re.compile(r'^\s*include\("([^"]+)"\)\s*$', re.MULTILINE)
PRODUCTION_PROJECT_RE = re.compile(
    r'^\s*(?:api|implementation|runtimeOnly)\s*\('
    r'\s*project\(\s*":?([A-Za-z0-9_-]+)"\s*\)\s*\)',
    re.MULTILINE,
)
SHORT_HINT = {"common": "公共上下文与工具", "prompts": "宿主提示词正文与组合", "core-shared": "技术基础设施",
              "core-foundation": "身份、组织与平台基础底座", "core-model": "平台模型目录与管理",
              "core-billing": "平台计费、配额与结算", "core-capability": "能力目录与发布",
              "core-agent": "平台 Agent 定义与装配", "core-chat": "平台会话与消息",
              "core-workflow": "工作流领域", "core-knowledge": "知识领域",
              "core-channel": "渠道领域", "migration": "Flyway 迁移",
              "institution-service": "机构服务（8000）",
              "platform-service": "平台服务（8100）",
              "gateway": "网关（8080）",
              "agent-runtime-api": "SDK 公开契约", "agent-runtime-codec-spi": "SDK 结果编解码契约",
              "agent-runtime-session-spi": "SDK 协调与存储契约", "agent-runtime-core": "SDK 纯计算内核",
              "agent-runtime-session": "SDK 会话与执行协调", "agent-runtime-memory": "SDK 记忆治理",
              "agent-runtime-adapter-testkit": "SDK 测试夹具与内存参考实现",
              "agent-runtime-adapter-jdbc": "Runtime PostgreSQL 存储与 schema",
              "agent-runtime-adapter-sqlite": "Runtime SQLite 存储",
              "agent-runtime-adapter-model": "模型供应商适配", "agent-runtime-adapter-mcp": "MCP 协议适配",
              "agent-runtime-spring-boot-starter": "SDK Spring 装配",
              "agent-runtime-desktop-host": "桌面 SDK 宿主", "agent-runtime-bom": "SDK 版本集合",
              "execution-contract": "宿主执行服务契约", "sandbox-service": "独立代码沙箱服务",
              "browser-service": "独立浏览器服务", "system-agent-runtime": "平台系统用途 Agent 装配"}


def hint(module: str) -> str:
    return SHORT_HINT.get(module.removeprefix("skillforge-"), "")


def collect_modules() -> list[str]:
    text = (BACKEND / "settings.gradle.kts").read_text(encoding="utf-8")
    return [m for m in INCLUDE_RE.findall(text)]


def collect_deps(module: str) -> list[str]:
    bg = BACKEND / module / "build.gradle.kts"
    if not bg.exists():
        return []
    text = bg.read_text(encoding="utf-8")
    return sorted(set(PRODUCTION_PROJECT_RE.findall(text)))


def render_graph(modules: list[str], deps: dict[str, list[str]]) -> str:
    lines = [GEN_HEADER, "# 后端模块依赖图（生成式）", "",
             "> 本文件由 `tools/docs/gen_module_graph.py` 生成，禁止手改。",
             "> 模块清单来自 `backend-java/settings.gradle.kts`，依赖来自各模块",
             "> `build.gradle.kts` 的 `api`、`implementation` 与 `runtimeOnly`",
             "> `project(...)` 声明；测试依赖不进入本图。运行边界见",
             "> [`01-技术架构.md`](../../02-架构与设计/01-技术架构.md)。",
             "", "```mermaid", "flowchart TD",
             "    %% 模块依赖：A --> B 表示 A 依赖 B（方向为运行时依赖）"]
    for m in modules:
        label = f"{m}<br/><small>{hint(m)}</small>"
        lines.append(f"    {m}[\"{label}\"]")
    for m in modules:
        for d in deps.get(m, []):
            if d in modules:
                lines.append(f"    {m} --> {d}")
    lines += ["```", "", "## 模块清单与依赖", "",
              "| 模块 | 职责 | 直接依赖 |",
              "| :--- | :--- | :--- |"]
    for m in modules:
        ds = deps.get(m, [])
        lines.append(f"| `{m}` | {hint(m) or '—'} | "
                     f"{'、'.join(f'`{d}`' for d in ds) if ds else '—'} |")
    lines += ["", "## 生成方式", "",
              "```bash", "make docs-regenerate   # 或 python tools/docs/gen_module_graph.py",
              "```", ""]
    return "\n".join(lines)


def main() -> int:
    check_only = "--check" in sys.argv
    modules = collect_modules()
    deps = {m: collect_deps(m) for m in modules}
    content = render_graph(modules, deps)

    if check_only:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != content:
            print(f"[FAIL] module-graph.md 已过时，请运行 make docs-regenerate")
            return 1
        print(f"[OK] module-graph.md 新鲜（{len(modules)} 个模块）")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content, encoding="utf-8")
    print(f"[OK] 已生成 {OUT.relative_to(ROOT)}（{len(modules)} 个模块）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
