package com.skillforge.runtime.core;

import java.io.File;
import java.io.IOException;
import java.lang.reflect.Modifier;
import java.net.URL;
import java.net.URLClassLoader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.jar.JarFile;

/**
 * Core test-only ABI 工具：只发现 Core JAR，以显式依赖 JAR 解析签名，不复用测试运行类路径。
 * 独立 loader 禁止测试运行类路径补齐缺失依赖；只有显式 generate 会更新受版本控制的基线。
 */
public final class CoreBaselineTool {
    private static final String PREFIX = "com/skillforge/runtime/core/";
    private static final int BATCH = 32;
    private static final String HEADER = """
            # Agent Runtime Core public ABI baseline v1
            # Generated by CoreBaselineTool with JDK 21 javap -public -s.
            # Update intentionally with :agent-runtime-core:generateCoreBaseline.
            """;

    /** 工具不持有运行状态或 Core 生产依赖。 */
    private CoreBaselineTool() { }

    /** 支持单依赖夹具与生产 API、Codec SPI、JSON 显式依赖，参数数量严格区分写入权限。 */
    public static void main(String[] args) throws Exception {
        if (Runtime.version().feature() != 21) { throw new IllegalStateException("Core ABI requires JDK 21"); }
        boolean generate = args.length > 0 && args[0].equals("generate");
        boolean verify = args.length > 0 && args[0].equals("verify");
        boolean valid = generate && (args.length >= 4 && args.length <= 6)
                || verify && (args.length >= 5 && args.length <= 7);
        if (!valid) {
            throw new IllegalArgumentException(
                    "expected generate <coreJar> <dependencyJar>... <baseline> "
                            + "or verify <coreJar> <dependencyJar>... <baseline> <report>");
        }
        Path core = Path.of(args[1]);
        int baselineIndex = args.length - (verify ? 2 : 1);
        List<Path> dependencies = Arrays.stream(args, 2, baselineIndex).map(Path::of).toList();
        Path baseline = Path.of(args[baselineIndex]);
        // verify 缺基线立即拒绝，避免 report 通过链接意外创建一个会被自己接受的 baseline。
        if (verify && !Files.isRegularFile(baseline)) { throw new IllegalStateException("Core baseline is missing"); }
        Path output = verify ? Path.of(args[baselineIndex + 1]) : baseline;
        distinct(output, core);
        for (Path dependency : dependencies) { distinct(output, dependency); }
        if (verify) { distinct(output, baseline); }
        String snapshot = snapshot(core, dependencies);
        Files.createDirectories(output.toAbsolutePath().getParent());
        Files.writeString(output, snapshot, StandardCharsets.UTF_8);
        if (verify && !normalize(Files.readString(baseline, StandardCharsets.UTF_8)).equals(snapshot)) {
            throw new IllegalStateException("Core ABI baseline mismatch; inspect " + output.toAbsolutePath());
        }
        System.out.println(verify ? "Verified Core public/nested/sealed ABI baseline" : "Generated Core public/nested/sealed ABI baseline");
    }

    /** 只扫描 Core 构件；依赖构件不能混入 inventory，也不允许空包产生合法空基线。 */
    static String snapshot(Path core, Path api) throws Exception {
        return snapshot(core, List.of(api));
    }

    /** 所有签名依赖都必须显式给出；测试 JVM 与环境 classpath 不能补齐遗漏。 */
    private static String snapshot(Path core, List<Path> dependencies) throws Exception {
        if (!Files.isRegularFile(core)
                || dependencies.isEmpty()
                || dependencies.stream().anyMatch(path -> !Files.isRegularFile(path))) {
            throw new IllegalArgumentException("Core and dependency jars are required");
        }
        List<String> candidates;
        try (var jar = new JarFile(core.toFile())) {
            candidates = jar.stream().filter(entry -> !entry.isDirectory()).map(entry -> entry.getName())
                    .filter(name -> name.startsWith(PREFIX) && name.endsWith(".class"))
                    .map(name -> name.substring(0, name.length() - 6).replace('/', '.')).distinct().sorted().toList();
        }
        var names = new ArrayList<String>();
        var permits = new ArrayList<String>();
        var classpathEntries = new ArrayList<Path>();
        classpathEntries.add(core);
        classpathEntries.addAll(dependencies);
        URL[] urls = classpathEntries.stream().map(path -> {
            try {
                return path.toUri().toURL();
            } catch (IOException exception) {
                throw new IllegalArgumentException("invalid ABI classpath entry", exception);
            }
        }).toArray(URL[]::new);
        try (var loader = new URLClassLoader(urls, ClassLoader.getPlatformClassLoader())) {
            for (String name : candidates) {
                var type = Class.forName(name, false, loader);
                if (!accessible(type)) { continue; }
                // 强制解析成员和泛型依赖，不能把 class 可加载误认为签名完整可用。
                resolveSignatures(type);
                names.add(name);
                if (type.isSealed()) {
                    var children = type.getPermittedSubclasses();
                    if (children.length == 0) { throw new IllegalStateException("sealed permits unavailable: " + name); }
                    permits.add(name + " -> " + String.join(",", Arrays.stream(children).map(Class::getName).sorted().toList()));
                }
            }
        }
        if (names.isEmpty()) { throw new IllegalStateException("Core public inventory must not be empty"); }
        StringBuilder result = new StringBuilder(HEADER).append("\n== PUBLIC TYPES ==\n").append(String.join("\n", names))
                .append("\n\n== SEALED PERMITS ==\n").append(String.join("\n", permits)).append("\n\n== JAVAP -public -s ==\n");
        String classpath = String.join(File.pathSeparator,
                classpathEntries.stream().map(path -> path.toAbsolutePath().toString()).toList());
        for (int start = 0; start < names.size(); start += BATCH) {
            var command = new ArrayList<>(List.of(javap().toString(), "-J-Duser.language=en", "-J-Duser.country=US", "-J-Dfile.encoding=UTF-8",
                    "-classpath", classpath, "-public", "-s"));
            command.addAll(names.subList(start, Math.min(start + BATCH, names.size())));
            // 参数数组直传进程，嵌套类的 $ 和包含空格的本机路径不经过 shell 插值。
            var process = new ProcessBuilder(command).redirectErrorStream(true).start();
            String text = new String(process.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
            if (process.waitFor() != 0) { throw new IllegalStateException("Core javap failed: " + text.strip()); }
            var lines = normalize(text).lines().filter(line -> !(line.startsWith("Compiled from \"") && line.endsWith("\"")))
                    .map(String::stripTrailing).toList();
            result.append(String.join("\n", lines).stripTrailing()).append('\n');
        }
        return result.toString().stripTrailing() + "\n";
    }

    /** 必须连同 enclosing chain 可见；私有实现中的 public 回调类不是组件 ABI。 */
    private static boolean accessible(Class<?> type) {
        return Modifier.isPublic(type.getModifiers()) && (type.getEnclosingClass() == null || accessible(type.getEnclosingClass()));
    }

    /** 读取真实公开成员的泛型/异常声明，缺失依赖直接失败而不借用测试 JVM 中的同名类。 */
    private static void resolveSignatures(Class<?> type) {
        type.getGenericSuperclass(); type.getGenericInterfaces(); type.getTypeParameters();
        for (var method : type.getMethods()) { method.getGenericReturnType(); method.getGenericParameterTypes(); method.getGenericExceptionTypes(); }
        for (var field : type.getFields()) { field.getGenericType(); }
        for (var constructor : type.getConstructors()) { constructor.getGenericParameterTypes(); constructor.getGenericExceptionTypes(); }
    }

    /** 定位运行本工具的 JDK21，不依赖 PATH 中另一版本的 javap。 */
    private static Path javap() {
        for (String name : List.of("javap", "javap.exe")) {
            Path path = Path.of(System.getProperty("java.home"), "bin", name);
            if (Files.isRegularFile(path)) { return path; }
        }
        throw new IllegalStateException("JDK javap not found");
    }

    /** 只容忍平台换行，基线正文和末尾仍精确比较。 */
    private static String normalize(String value) { return value.replace("\r\n", "\n").replace('\r', '\n'); }

    /** 输入 JAR 和受控基线不能被 report/生成目标经规范路径、软/硬链接别名覆盖。 */
    private static void distinct(Path output, Path input) throws IOException {
        if (output.toAbsolutePath().normalize().equals(input.toAbsolutePath().normalize())
                || Files.exists(output) && Files.exists(input) && Files.isSameFile(output, input)) {
            throw new IllegalArgumentException("ABI output must not alias an input");
        }
    }
}
