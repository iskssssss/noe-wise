package com.skillforge.runtime.memory;

import java.io.File;
import java.io.IOException;
import java.lang.reflect.Modifier;
import java.net.URL;
import java.net.URLClassLoader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.jar.JarFile;

/**
 * Memory 测试专用 ABI 工具：只发现 Memory JAR，并且只用 API JAR 解析签名依赖。
 * 独立 loader 禁止测试类路径补齐缺失依赖；只有显式 generate 会更新受控基线。
 */
public final class MemoryBaselineTool {
    private static final String PREFIX = "com/skillforge/runtime/memory/";
    private static final int BATCH = 32;
    private static final String HEADER = """
            # Agent Runtime Memory public ABI baseline v1
            # Generated by MemoryBaselineTool with JDK 21 javap -public -s.
            # Update intentionally with :agent-runtime-memory:generateMemoryBaseline.
            """;

    private MemoryBaselineTool() { }

    /** verify memoryJar apiJar baseline report；generate memoryJar apiJar baseline。 */
    public static void main(String[] args) throws Exception {
        if (Runtime.version().feature() != 21) {
            throw new IllegalStateException("Memory ABI requires JDK 21");
        }
        boolean generate = args.length == 4 && args[0].equals("generate");
        boolean verify = args.length == 5 && args[0].equals("verify");
        if (!generate && !verify) {
            throw new IllegalArgumentException(
                    "expected generate <memoryJar> <apiJar> <baseline> or verify <memoryJar> <apiJar> <baseline> <report>");
        }
        Path memory = Path.of(args[1]);
        Path api = Path.of(args[2]);
        Path baseline = Path.of(args[3]);
        if (verify && !Files.isRegularFile(baseline)) {
            throw new IllegalStateException("Memory baseline is missing");
        }
        Path output = verify ? Path.of(args[4]) : baseline;
        distinct(output, memory);
        distinct(output, api);
        if (verify) {
            distinct(output, baseline);
        }
        String snapshot = snapshot(memory, api);
        Files.createDirectories(output.toAbsolutePath().getParent());
        Files.writeString(output, snapshot, StandardCharsets.UTF_8);
        if (verify && !normalize(Files.readString(baseline, StandardCharsets.UTF_8)).equals(snapshot)) {
            throw new IllegalStateException("Memory ABI baseline mismatch; inspect " + output.toAbsolutePath());
        }
        System.out.println(verify
                ? "Verified Memory public/nested/sealed ABI baseline"
                : "Generated Memory public/nested/sealed ABI baseline");
    }

    /** 只扫描 Memory 构件；API 依赖不能混入公开类型清单。 */
    static String snapshot(Path memory, Path api) throws Exception {
        if (!Files.isRegularFile(memory) || !Files.isRegularFile(api)) {
            throw new IllegalArgumentException("Memory and API jars are required");
        }
        List<String> candidates;
        try (var jar = new JarFile(memory.toFile())) {
            candidates = jar.stream()
                    .filter(entry -> !entry.isDirectory())
                    .map(entry -> entry.getName())
                    .filter(name -> name.startsWith(PREFIX) && name.endsWith(".class"))
                    .map(name -> name.substring(0, name.length() - 6).replace('/', '.'))
                    .distinct().sorted().toList();
        }
        var names = new ArrayList<String>();
        var permits = new ArrayList<String>();
        try (var loader = new URLClassLoader(
                new URL[] {memory.toUri().toURL(), api.toUri().toURL()},
                ClassLoader.getPlatformClassLoader())) {
            for (String name : candidates) {
                Class<?> type = Class.forName(name, false, loader);
                if (!accessible(type)) {
                    continue;
                }
                resolveSignatures(type);
                names.add(name);
                if (type.isSealed()) {
                    Class<?>[] children = type.getPermittedSubclasses();
                    if (children.length == 0) {
                        throw new IllegalStateException("sealed permits unavailable: " + name);
                    }
                    permits.add(name + " -> " + String.join(",",
                            Arrays.stream(children).map(Class::getName).sorted().toList()));
                }
            }
        }
        if (names.isEmpty()) {
            throw new IllegalStateException("Memory public inventory must not be empty");
        }
        StringBuilder result = new StringBuilder(HEADER)
                .append("\n== PUBLIC TYPES ==\n").append(String.join("\n", names))
                .append("\n\n== SEALED PERMITS ==\n").append(String.join("\n", permits))
                .append("\n\n== JAVAP -public -s ==\n");
        for (int start = 0; start < names.size(); start += BATCH) {
            var command = new ArrayList<>(List.of(
                    javap().toString(), "-J-Duser.language=en", "-J-Duser.country=US",
                    "-J-Dfile.encoding=UTF-8", "-classpath",
                    memory.toAbsolutePath() + File.pathSeparator + api.toAbsolutePath(), "-public", "-s"));
            command.addAll(names.subList(start, Math.min(start + BATCH, names.size())));
            var process = new ProcessBuilder(command).redirectErrorStream(true).start();
            String text = new String(process.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
            if (process.waitFor() != 0) {
                throw new IllegalStateException("Memory javap failed: " + text.strip());
            }
            List<String> lines = normalize(text).lines()
                    .filter(line -> !(line.startsWith("Compiled from \"") && line.endsWith("\"")))
                    .map(String::stripTrailing).toList();
            result.append(String.join("\n", lines).stripTrailing()).append('\n');
        }
        return result.toString().stripTrailing() + "\n";
    }

    private static boolean accessible(Class<?> type) {
        return Modifier.isPublic(type.getModifiers())
                && (type.getEnclosingClass() == null || accessible(type.getEnclosingClass()));
    }

    /** 强制解析全部公开签名，缺失依赖不能被测试 JVM 隐式补齐。 */
    private static void resolveSignatures(Class<?> type) {
        type.getGenericSuperclass();
        type.getGenericInterfaces();
        type.getTypeParameters();
        for (var method : type.getMethods()) {
            method.getGenericReturnType();
            method.getGenericParameterTypes();
            method.getGenericExceptionTypes();
        }
        for (var field : type.getFields()) {
            field.getGenericType();
        }
        for (var constructor : type.getConstructors()) {
            constructor.getGenericParameterTypes();
            constructor.getGenericExceptionTypes();
        }
    }

    private static Path javap() {
        for (String name : List.of("javap", "javap.exe")) {
            Path path = Path.of(System.getProperty("java.home"), "bin", name);
            if (Files.isRegularFile(path)) {
                return path;
            }
        }
        throw new IllegalStateException("JDK javap not found");
    }

    private static String normalize(String value) {
        return value.replace("\r\n", "\n").replace('\r', '\n');
    }

    private static void distinct(Path output, Path input) throws IOException {
        if (output.toAbsolutePath().normalize().equals(input.toAbsolutePath().normalize())
                || Files.exists(output) && Files.exists(input) && Files.isSameFile(output, input)) {
            throw new IllegalArgumentException("ABI output must not alias an input");
        }
    }
}
