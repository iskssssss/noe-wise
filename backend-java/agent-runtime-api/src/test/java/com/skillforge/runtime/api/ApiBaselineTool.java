package com.skillforge.runtime.api;

import java.io.IOException;
import java.lang.reflect.Modifier;
import java.net.URL;
import java.net.URLClassLoader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Locale;
import java.util.jar.JarFile;

/**
 * 从最终 Agent Runtime API JAR 生成或校验可重复的公开 ABI 基线。
 *
 * <p>工具只使用 JDK 21 的反射与 {@code javap -public -s}，不依赖测试框架、
 * 网络插件或宿主模块。验证模式只写入 build report，只有显式生成模式会改写受控基线。</p>
 */
public final class ApiBaselineTool {

    private static final String API_ENTRY_PREFIX = "com/skillforge/runtime/api/";
    private static final int JAVAP_BATCH_SIZE = 32;
    private static final String HEADER = """
            # Agent Runtime API public ABI baseline v1
            # Generated by ApiBaselineTool with JDK 21 javap -public -s.
            # Update intentionally with :agent-runtime-api:generateApiBaseline.
            """;

    /** 工具类不承担实例状态。 */
    private ApiBaselineTool() {
    }

    /**
     * 按 {@code verify <jar> <baseline> <report>} 或 {@code generate <jar> <baseline>} 执行。
     *
     * @param arguments 显式模式及路径参数
     * @throws Exception JAR 加载、JDK 工具或文件操作失败
     */
    public static void main(String[] arguments) throws Exception {
        requireJdk21();
        if (arguments.length == 0) {
            throw new IllegalArgumentException("mode is required: verify or generate");
        }

        // 模式必须显式区分只读校验和受控更新，防止 check 隐式接受 ABI 变更。
        switch (arguments[0]) {
            case "verify" -> {
                requireArgumentCount(arguments, 4);
                verify(Path.of(arguments[1]), Path.of(arguments[2]), Path.of(arguments[3]));
            }
            case "generate" -> {
                requireArgumentCount(arguments, 3);
                generate(Path.of(arguments[1]), Path.of(arguments[2]));
            }
            default -> throw new IllegalArgumentException("unsupported mode: " + arguments[0]);
        }
    }

    /** 要求基线工具由 JDK 21 运行，避免跨 major 版本的 javap 格式假差异。 */
    private static void requireJdk21() {
        if (Runtime.version().feature() != 21) {
            throw new IllegalStateException(
                    "ApiBaselineTool requires JDK 21, but is running on " + Runtime.version());
        }
    }

    /** 校验模式的参数数量，避免错误路径被当成生成目标。 */
    private static void requireArgumentCount(String[] arguments, int expected) {
        if (arguments.length != expected) {
            throw new IllegalArgumentException(
                    "mode " + arguments[0] + " requires " + (expected - 1) + " path arguments");
        }
    }

    /** 确认基线存在后生成当前 ABI report 并比较，不修改基线。 */
    private static void verify(Path jarPath, Path baselinePath, Path reportPath) throws Exception {
        // 缺失基线时禁止任何输出，避免悬空 report 链接间接创建 baseline 后造成假绿。
        if (!Files.isRegularFile(baselinePath)) {
            throw new IllegalStateException("API baseline is missing: " + baselinePath.toAbsolutePath());
        }
        // 比较前拒绝输出与任一输入同址，包括规范化路径、符号链接和硬链接别名。
        requireDistinctOutput(reportPath, baselinePath);
        requireDistinctOutput(reportPath, jarPath);
        BaselineSnapshot snapshot = buildSnapshot(jarPath);
        writeCanonicalFile(reportPath, snapshot.content());

        // 仅容忍 Git 在 Windows checkout 产生的 CRLF；行尾空白和文件末尾仍必须精确匹配。
        String expected = normalizeLineSeparators(Files.readString(baselinePath, StandardCharsets.UTF_8));
        if (!expected.equals(snapshot.content())) {
            int line = firstDifferentLine(expected, snapshot.content());
            throw new IllegalStateException(
                    "Agent Runtime API baseline mismatch at line " + line
                            + "; inspect " + reportPath.toAbsolutePath()
                            + " and run :agent-runtime-api:generateApiBaseline only after ABI review");
        }
        System.out.printf(
                Locale.ROOT,
                "Verified API baseline: %d public types, %d sealed types.%n",
                snapshot.publicTypeCount(),
                snapshot.sealedTypeCount());
    }

    /** 显式生成模式以 LF 和 UTF-8 覆写受控基线。 */
    private static void generate(Path jarPath, Path baselinePath) throws Exception {
        // 显式更新授权只适用于 baseline，不允许把输入 JAR 当作生成目标。
        requireDistinctOutput(baselinePath, jarPath);
        BaselineSnapshot snapshot = buildSnapshot(jarPath);
        writeCanonicalFile(baselinePath, snapshot.content());
        System.out.printf(
                Locale.ROOT,
                "Generated API baseline: %d public types, %d sealed types.%n",
                snapshot.publicTypeCount(),
                snapshot.sealedTypeCount());
    }

    /** 从最终 JAR 建立类型清单、sealed permits 和 javap 签名三段式快照。 */
    private static BaselineSnapshot buildSnapshot(Path jarPath) throws Exception {
        if (!Files.isRegularFile(jarPath)) {
            throw new IllegalArgumentException("API jar does not exist: " + jarPath.toAbsolutePath());
        }
        ReflectionInventory inventory = inspectPublicTypes(jarPath);
        StringBuilder content = new StringBuilder(HEADER);
        content.append('\n').append("== PUBLIC TYPES ==").append('\n');
        inventory.publicTypeNames().forEach(name -> content.append(name).append('\n'));
        content.append('\n').append("== SEALED PERMITS ==").append('\n');
        inventory.sealedPermitLines().forEach(line -> content.append(line).append('\n'));
        content.append('\n').append("== JAVAP -public -s ==").append('\n');
        content.append(runJavap(jarPath, inventory.publicTypeNames()));

        // 三段内容最终收敛为单一 LF，防止批次边界引入多余空行。
        String canonical = content.toString().stripTrailing() + "\n";
        return new BaselineSnapshot(
                canonical,
                inventory.publicTypeNames().size(),
                inventory.sealedPermitLines().size());
    }

    /** 扫描 JAR 中 API 包的全部 class，并以 JVM public access flag 确定顶层与 nested ABI。 */
    private static ReflectionInventory inspectPublicTypes(Path jarPath) throws Exception {
        List<String> candidateNames;
        try (JarFile jar = new JarFile(jarPath.toFile())) {
            candidateNames = jar.stream()
                    .filter(entry -> !entry.isDirectory())
                    .map(entry -> entry.getName())
                    .filter(name -> name.startsWith(API_ENTRY_PREFIX) && name.endsWith(".class"))
                    .map(ApiBaselineTool::toBinaryName)
                    .distinct()
                    .sorted()
                    .toList();
        }

        List<String> publicTypeNames = new ArrayList<>();
        List<String> sealedPermitLines = new ArrayList<>();
        URL jarUrl = jarPath.toUri().toURL();
        try (URLClassLoader loader = new URLClassLoader(
                new URL[] {jarUrl}, ClassLoader.getPlatformClassLoader())) {
            for (String candidateName : candidateNames) {
                Class<?> candidate = Class.forName(candidateName, false, loader);
                if (!Modifier.isPublic(candidate.getModifiers())) {
                    continue;
                }
                publicTypeNames.add(candidate.getName());
                if (candidate.isSealed()) {
                    String permits = Arrays.stream(candidate.getPermittedSubclasses())
                            .map(Class::getName)
                            .sorted()
                            .reduce((left, right) -> left + "," + right)
                            .orElse("");
                    sealedPermitLines.add(candidate.getName() + " -> " + permits);
                }
            }
        }
        return new ReflectionInventory(List.copyOf(publicTypeNames), List.copyOf(sealedPermitLines));
    }

    /** 把 JAR entry 路径转为保留 {@code $} 的 JVM binary FQN。 */
    private static String toBinaryName(String entryName) {
        return entryName.substring(0, entryName.length() - ".class".length()).replace('/', '.');
    }

    /** 按排序后的 binary FQN 分批调用 javap，避免 Windows 命令行长度上限。 */
    private static String runJavap(Path jarPath, List<String> publicTypeNames)
            throws IOException, InterruptedException {
        StringBuilder output = new StringBuilder();
        Path javap = resolveJdkTool("javap");
        for (int start = 0; start < publicTypeNames.size(); start += JAVAP_BATCH_SIZE) {
            int end = Math.min(start + JAVAP_BATCH_SIZE, publicTypeNames.size());
            List<String> command = new ArrayList<>(JAVAP_BATCH_SIZE + 8);
            command.add(javap.toString());
            command.add("-J-Duser.language=en");
            command.add("-J-Duser.country=US");
            command.add("-J-Dfile.encoding=UTF-8");
            command.add("-classpath");
            command.add(jarPath.toAbsolutePath().toString());
            command.add("-public");
            command.add("-s");
            command.addAll(publicTypeNames.subList(start, end));

            // 参数数组直接传给进程，确保空格路径和 nested 类名中的 $ 不被 shell 解释。
            Process process = new ProcessBuilder(command)
                    .redirectErrorStream(true)
                    .start();
            String batchOutput = new String(
                    process.getInputStream().readAllBytes(),
                    StandardCharsets.UTF_8);
            int exitCode = process.waitFor();
            if (exitCode != 0) {
                throw new IllegalStateException(
                        "javap failed with exit code " + exitCode + ": " + batchOutput.strip());
            }
            output.append(canonicalizeJavap(batchOutput));
        }
        return output.toString();
    }

    /** 移除非 ABI 的 SourceFile 标题，统一换行并清理行尾空白。 */
    private static String canonicalizeJavap(String rawOutput) {
        List<String> lines = new ArrayList<>(Arrays.asList(
                normalizeLineSeparators(rawOutput).split("\n", -1)));
        lines.removeIf(line -> line.startsWith("Compiled from \"") && line.endsWith("\""));
        lines.replaceAll(String::stripTrailing);
        while (!lines.isEmpty() && lines.get(lines.size() - 1).isEmpty()) {
            lines.remove(lines.size() - 1);
        }
        return String.join("\n", lines) + "\n";
    }

    /** 仅将平台换行转换为 LF，不吞掉基线中其他可见差异。 */
    private static String normalizeLineSeparators(String value) {
        return value.replace("\r\n", "\n").replace('\r', '\n');
    }

    /** 从运行工具的 JDK 21 安装目录解析 Windows 或 Unix 可执行文件。 */
    private static Path resolveJdkTool(String toolName) {
        Path binDirectory = Path.of(System.getProperty("java.home"), "bin");
        for (String candidateName : List.of(toolName, toolName + ".exe")) {
            Path candidate = binDirectory.resolve(candidateName);
            if (Files.isRegularFile(candidate)) {
                return candidate;
            }
        }
        throw new IllegalStateException(
                "JDK 21 tool not found: " + toolName + " under " + binDirectory.toAbsolutePath());
    }

    /** 写入前比较规范路径和现存文件身份，拒绝覆盖输入或证据本身。 */
    private static void requireDistinctOutput(Path output, Path input) throws IOException {
        boolean samePath = output.toAbsolutePath().normalize().equals(input.toAbsolutePath().normalize());
        boolean sameFile = Files.exists(output) && Files.exists(input) && Files.isSameFile(output, input);
        if (samePath || sameFile) {
            throw new IllegalArgumentException("output must not alias an input: " + output.toAbsolutePath());
        }
    }

    /** 以 UTF-8 和已规范化的 LF 写入生成物或 build report。 */
    private static void writeCanonicalFile(Path path, String content) throws IOException {
        Path parent = path.toAbsolutePath().getParent();
        if (parent != null) {
            Files.createDirectories(parent);
        }
        Files.writeString(path, content, StandardCharsets.UTF_8);
    }

    /** 返回首个不同的一基行号，供校验失败时快速定位。 */
    private static int firstDifferentLine(String expected, String actual) {
        String[] expectedLines = expected.split("\n", -1);
        String[] actualLines = actual.split("\n", -1);
        int commonLength = Math.min(expectedLines.length, actualLines.length);
        for (int index = 0; index < commonLength; index++) {
            if (!expectedLines[index].equals(actualLines[index])) {
                return index + 1;
            }
        }
        return commonLength + 1;
    }

    /** 保存反射发现的 public 类型和 sealed permits 行。 */
    private record ReflectionInventory(
            List<String> publicTypeNames,
            List<String> sealedPermitLines) {
    }

    /** 保存规范化 baseline 内容及可审计的类型计数。 */
    private record BaselineSnapshot(
            String content,
            int publicTypeCount,
            int sealedTypeCount) {
    }
}
