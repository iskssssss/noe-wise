package com.skillforge.runtime.adapter.jdbc.schema;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Base64;
import org.apache.ibatis.builder.xml.XMLMapperBuilder;
import org.apache.ibatis.mapping.Environment;
import org.apache.ibatis.session.Configuration;
import org.apache.ibatis.session.SqlSessionFactoryBuilder;
import org.apache.ibatis.transaction.jdbc.JdbcTransactionFactory;
import org.flywaydb.core.Flyway;
import org.postgresql.ds.PGSimpleDataSource;
import org.testcontainers.containers.PostgreSQLContainer;

/** 从独立临时 PostgreSQL 的正式迁移和结构查询生成清单；不接收外部数据库连接。 */
public final class RuntimeSchemaManifestExporter {
    private RuntimeSchemaManifestExporter() { }

    public static void main(String[] args) throws Exception {
        if (args.length != 1) throw new IllegalArgumentException("需要唯一的清单输出路径");
        Path output = Path.of(args[0]);
        try (var postgres = new PostgreSQLContainer<>("pgvector/pgvector:pg16")
                .withDatabaseName("runtime_manifest").withUsername("manifest_owner")
                .withPassword("manifest_test_password")) {
            postgres.start();
            var source = new PGSimpleDataSource();
            source.setURL(postgres.getJdbcUrl());
            source.setUser(postgres.getUsername());
            source.setPassword(postgres.getPassword());
            // 导出阶段不能依赖尚未更新的清单，但迁移位置与正式入口一致。
            Flyway.configure().dataSource(source).defaultSchema("public")
                    .locations(RuntimeJdbcSchema.MIGRATION_LOCATION)
                    .table(RuntimeJdbcSchema.HISTORY_TABLE).cleanDisabled(true).load().migrate();
            var configuration = new Configuration(new Environment("manifest-export",
                    new JdbcTransactionFactory(), source));
            String mapper = "mapper/AgentRuntimeSchemaMapper.xml";
            try (var resource = RuntimeSchemaManifestExporter.class.getClassLoader().getResourceAsStream(mapper)) {
                if (resource == null) throw new IllegalStateException("结构查询资源不存在");
                new XMLMapperBuilder(resource, configuration, mapper, configuration.getSqlFragments()).parse();
            }
            try (var session = new SqlSessionFactoryBuilder().build(configuration).openSession()) {
                var entries = session.getMapper(RuntimeSchemaMapper.class).structure();
                if (entries.isEmpty()) throw new IllegalStateException("拒绝导出空结构清单");
                var content = new StringBuilder("# Generated by :agent-runtime-adapter-jdbc:exportRuntimeSchemaManifest\n");
                for (var entry : entries) {
                    content.append(entry.kind()).append('\t').append(entry.name()).append('\t')
                            .append(Base64.getEncoder().encodeToString(entry.definition().getBytes(StandardCharsets.UTF_8)))
                            .append('\n');
                }
                Files.createDirectories(output.toAbsolutePath().getParent());
                Files.writeString(output, content, StandardCharsets.UTF_8);
                System.out.println("Runtime schema entries=" + entries.size() + " output=" + output);
            }
        }
    }
}
